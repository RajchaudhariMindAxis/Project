
import apiClient from "../../../../../../API/apiClient";
import { API_ENDPOINTS } from "../../../../../../API/apiConfig";
import type { PriceList, PriceListListItem } from "./types";

const endpoint = API_ENDPOINTS.PriceList;

const normalizePriceList = (item: any): PriceList => ({
  priceListId: Number(item.priceListId ?? item.PriceListId ?? 0),
  code: item.code ?? item.Code ?? "",
  name: item.name ?? item.Name ?? "",
  customerChannelType:
    item.customerChannelType ?? item.CustomerChannelType ?? "",
  // Keep the existing frontend property "id", while mapping
  // the backend's CurrencyId correctly.
  id: Number(item.currencyId ?? item.CurrencyId ?? item.id ?? item.Id ?? 0),
  effectiveFrom: item.effectiveFrom ?? item.EffectiveFrom ?? "",
  effectiveTo: item.effectiveTo ?? item.EffectiveTo ?? null,
  isActive: Boolean(item.isActive ?? item.IsActive ?? false),
  isDeleted: Boolean(item.isDeleted ?? item.IsDeleted ?? false),
});

export const getPriceLists = async (): Promise<PriceListListItem[]> => {
  const response = await apiClient.get(endpoint);
  const result = response.data?.data ?? response.data;

  return Array.isArray(result)
    ? result.map(normalizePriceList)
    : [];
};

/**
 * Calls GET /api/PriceList/generate-code.
 * Example: { code: "LGM-PRL-0001" }
 */
export const getGeneratedPriceListCode = async (): Promise<string> => {
  const response = await apiClient.get(`${endpoint}/generate-code`);
  const result = response.data?.data ?? response.data;

  const code =
    typeof result === "string"
      ? result
      : result?.code ?? result?.Code;

  if (typeof code !== "string" || !code.trim()) {
    throw new Error("The Price List code API returned an invalid code.");
  }

  return code.trim();
};

export const getPriceListById = async (
  id: number
): Promise<PriceList> => {
  const response = await apiClient.get(`${endpoint}/${id}`);
  const result = response.data?.data ?? response.data;

  return normalizePriceList(result);
};

export const savePriceList = async (
  data: PriceList
): Promise<void> => {
  // Use the existing code when editing. For a new record, use the
  // code already generated by the form, or request one as a fallback.
  const code =
    data.priceListId > 0
      ? data.code.trim()
      : data.code.trim() || await getGeneratedPriceListCode();

  const payload = {
    priceListId: data.priceListId || 0,
    code,
    name: data.name.trim(),
    customerChannelType: data.customerChannelType.trim(),
    currencyId: Number(data.id),
    effectiveFrom: data.effectiveFrom,
    effectiveTo: data.effectiveTo || null,
    isActive: data.isActive,
    isDeleted: data.isDeleted ?? false,
  };

  if (data.priceListId > 0) {
    await apiClient.put(`${endpoint}/${data.priceListId}`, payload);
  } else {
    await apiClient.post(endpoint, payload);
  }
};

export const deletePriceList = async (id: number): Promise<void> => {
  await apiClient.delete(`${endpoint}/${id}`);
};

import type { CurrencyOption } from "./types";

export const getCurrencies = async (): Promise<CurrencyOption[]> => {
  const response = await apiClient.get(API_ENDPOINTS.Currency);
  const result = response.data?.data ?? response.data;

  if (!Array.isArray(result)) return [];

  return result.map((item: any) => ({
    id: Number(
      item.id ?? item.Id ?? item.currencyId ?? item.CurrencyId
    ),
    currencyName:
      item.currencyName ?? item.CurrencyName ?? item.name ?? item.Name ?? "",
    currencySymbol:
      item.currencySymbol ?? item.CurrencySymbol ?? item.symbol ?? item.Symbol ?? "",
  }));
};